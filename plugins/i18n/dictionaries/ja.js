const t = (value) => entries[value] ?? value;
const feedState = { ON: 'オン', OFF: 'オフ', LOADING: '読み込み中', DEGRADED: '低下', STALE: '古い', PARTIAL: '部分的', FALLBACK: '代替', UNAVAILABLE: '利用不可', UNCERTAIN: '不確定' };

// Strings the app composes at runtime. Non-global regexes only (see translate.js).
const patterns = [
  [/^Expand (.+)$/, (name) => `${t(name)} を開く`],
  [/^Collapse (.+)$/, (name) => `${t(name)} を閉じる`],
  [
    /^(\S+) · (ON|OFF) · ([\d.]+)s \+ ([\d.]+)s$/,
    (style, flag, hold, travel) =>
      `${t(style)} · ${feedState[flag]} · ${hold}秒 ＋ ${travel}秒`,
  ],
  [/^(.+) unavailable: (.+)$/, (name, reason) => `${t(name)} は利用できません: ${t(reason)}`],
  [/^(.+): (ON|OFF|LOADING|DEGRADED|STALE|PARTIAL|FALLBACK|UNAVAILABLE|UNCERTAIN)$/, (name, flag) => `${t(name)}: ${feedState[flag]}`],
  [/^(.+) · never$/, (source) => `${t(source)} · 未取得`],
  [/^Detection overlay: (.+)$/, (mode) => `探知オーバーレイ: ${t(mode)}`],
  [/^paste (.+)$/, (key) => `${key} を貼り付け`],
  [/^POWER UP · (\d+) KEYS? WAITING$/, (count) => `パワーアップ · 未設定キー ${count} 件`],
  [/^📍 Location: (.+)$/, (place) => `📍 現在地: ${place}`],
  [/^Landmark: (.+)$/, (place) => `ランドマーク: ${place}`],
  [/^Flying to (.+)\.\.\.$/, (place) => `${place} へ移動中...`],
  [/^PAGE (\d+)\/(\d+)$/, (page, total) => `ページ ${page}/${total}`],
  [
    /^Reset map to north up\. Current heading (\S+) degrees$/,
    (degrees) => `マップを北上向きに戻す。現在の方位 ${degrees} 度`,
  ],
  [
    /^Voice model: (\S+) — click to switch to (\S+); applies next session$/,
    (current, next) => `音声モデル: ${current} — クリックで ${next} に切替、次のセッションから適用`,
  ],
  [
    /^Estimated session cost on (\S+) — (\d+) response\(s\)\. Warns at ~\$(\S+), ends the session at ~\$(\S+)\.$/,
    (model, responses, warn, stop) =>
      `${model} の推定セッション費用 — 応答 ${responses} 件。約 $${warn} で警告し、約 $${stop} でセッションを終了します。`,
  ],
];

export default { entries, patterns };
